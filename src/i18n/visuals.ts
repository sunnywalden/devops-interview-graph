// A single pass avoids replacing a translated fragment again. Longer phrases
// must win over shared short labels such as “是” or “匹配”.
const labelPattern = new RegExp(Object.keys(diagramEnglish)
  .sort((a, b) => b.length - a.length)
  .map(key => key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
  .join('|'), 'g');
function english(text: string): string {
  return text.replace(labelPattern, label => diagramEnglish[label]);
}
export function localizeVisual(visual: CardVisual): CardVisual {
  if (visual.kind === 'mermaid') {
    return { ...visual, title: english(visual.title), source: english(visual.source) };
  }
  return {
    ...visual, title: english(visual.title),
    nodes: visual.nodes.map(node => ({ ...node, label: english(node.label), detail: node.detail ? english(node.detail) : undefined })),
    edges: visual.edges.map(edge => ({ ...edge, label: edge.label ? english(edge.label) : undefined })),
  };
}
